export const CURRENCY_RATES: Record<Currency, { symbol: string; rate: number; label: string }> = {
  USD: { symbol: '$', rate: 1, label: 'USD ($)' },
  EUR: { symbol: '€', rate: 0.92, label: 'EUR (€)' },
  GBP: { symbol: '£', rate: 0.79, label: 'GBP (£)' },
  LKR: { symbol: 'Rs ', rate: 305, label: 'LKR (Rs)' },
};

export function formatPrice(priceInUsd: number, currency: Currency): string {
  const { symbol, rate } = CURRENCY_RATES[currency];
  const converted = Math.round(priceInUsd * rate);
  if (currency === 'LKR') {
    return `${symbol}${converted.toLocaleString()}`;
  }
  return `${symbol}${converted.toLocaleString()}`;
}

